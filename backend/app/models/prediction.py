"""
ORM models for predicted papers, predicted questions, and rubrics.

Generated by the prediction agent (7.6). Each predicted question
carries a checklist rubric used by the evaluation agent (7.7).
"""

from datetime import datetime

from sqlalchemy import DateTime, Float, ForeignKey, Integer, String, Text, func
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy import JSON

from app.database import Base


class PredictedPaper(Base):
    """A generated predicted examination paper."""

    __tablename__ = "predicted_papers"

    predicted_paper_id: Mapped[str] = mapped_column(String(128), primary_key=True)
    subject: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    target_marks: Mapped[int] = mapped_column(Integer, nullable=False)
    variant: Mapped[int] = mapped_column(Integer, default=1)  # v1, v2, v3...
    parent_paper_id: Mapped[str | None] = mapped_column(
        String(128), nullable=True
    )  # Links alternate variants to the primary
    generated_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now()
    )

    # Relationships
    questions: Mapped[list["PredictedQuestion"]] = relationship(
        back_populates="predicted_paper", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<PredictedPaper {self.predicted_paper_id}>"


class PredictedQuestion(Base):
    """A single question in a predicted paper, with its rubric."""

    __tablename__ = "predicted_questions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    predicted_paper_id: Mapped[str] = mapped_column(
        String(128),
        ForeignKey("predicted_papers.predicted_paper_id", ondelete="CASCADE"),
        nullable=False,
    )
    question_no: Mapped[str] = mapped_column(String(16), nullable=False)
    unit: Mapped[str] = mapped_column(String(128), nullable=False)
    text: Mapped[str] = mapped_column(Text, nullable=False)
    marks: Mapped[float] = mapped_column(Float, nullable=False)
    source: Mapped[str] = mapped_column(
        String(256), nullable=False
    )  # "generated" or "reused_from:{question_id}"
    similarity_flag: Mapped[str | None] = mapped_column(
        String(64), nullable=True
    )  # "near-duplicate", "twisted", null

    # Rubric checklist stored as JSON array of {point, weight}
    rubric: Mapped[dict | None] = mapped_column(JSON, nullable=True)

    # Relationships
    predicted_paper: Mapped["PredictedPaper"] = relationship(
        back_populates="questions"
    )

    def __repr__(self) -> str:
        return f"<PredictedQuestion Q{self.question_no} ({self.marks}m)>"
